"""Create the runnable vector example and the timeline used by native tests.

Run from a writable directory with Python 3 and ReportLab installed:
    python3 vector_animation.py --output-dir ./vector-example
    pdfpc vector-example/vector-animation.pdf
"""

import argparse
import json
from pathlib import Path


PAGE_SIZE = (640, 480)
REGION = (50, 110, 590, 434)  # PDF points, measured from the lower-left corner.
STEM = "vector-animation"


def timeline(scene_id="moving-square"):
    """Hold a square, move it right, then reduce its opacity."""
    def key(time, coords=None, opacity=1):
        state = {"time": time, "fill": [1, 0, 0, opacity],
                 "stroke": [0, 0, 0, 0], "stroke_width": 0}
        if coords is not None:
            state["coords"] = coords
        return state

    start = [10, 20, 30, 20, 30, 40, 10, 40]
    end = [70, 20, 90, 20, 90, 40, 70, 40]
    return {"version": 1, "scenes": [{
        "id": scene_id, "width": 100, "height": 60, "duration": 3,
        "background": [1, 1, 1, 1],
        "checkpoints": [{"time": 0, "label": "Initial"},
                        {"time": 1, "label": "Held"},
                        {"time": 2, "label": "Moved"},
                        {"time": 3, "label": "Faded"}],
        "objects": [{"id": "square", "z": 0, "commands": "MLLLZ",
                     "fill_rule": "nonzero", "keyframes": [
                         key(0, start), key(1), key(2, end), key(3, opacity=0.5)]}],
    }]}


def write_example(directory):
    from reportlab.pdfgen import canvas

    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    data = timeline()
    scene = data["scenes"][0]
    manifest = directory / (STEM + ".vector.json")
    manifest.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    pdf = directory / (STEM + ".pdf")
    document = canvas.Canvas(str(pdf), pagesize=PAGE_SIZE, invariant=1)
    document.setTitle("Vector animation example")
    document.setAuthor("pdfpc contributors")
    document.setFont("Helvetica", 22)
    document.drawString(50, 451, "Hold, move, fade")

    left, bottom, right, top = REGION
    document.saveState()
    document.translate(left, top)
    document.scale((right - left) / scene["width"],
                   -(top - bottom) / scene["height"])
    document.setFillColorRGB(*scene["background"][:3])
    document.rect(0, 0, scene["width"], scene["height"], stroke=0, fill=1)
    # The poster uses the same initial polygon as the live timeline.
    state = scene["objects"][0]["keyframes"][0]
    points = list(zip(state["coords"][::2], state["coords"][1::2]))
    polygon = document.beginPath()
    polygon.moveTo(*points[0])
    for point in points[1:]:
        polygon.lineTo(*point)
    polygon.close()
    document.setFillColorRGB(*state["fill"][:3])
    document.setFillAlpha(state["fill"][3])
    document.drawPath(polygon, stroke=0, fill=1)
    document.restoreState()

    # A URI link, not a movie annotation, binds the PDF region to its scene ID.
    document.linkURL("pdfpc-vector:" + scene["id"], REGION,
                     relative=0, thickness=0)
    document.setFillColorRGB(.15, .15, .15)
    document.setFont("Helvetica", 13)
    document.drawString(50, 80, "Right / Space: next checkpoint     Left: previous checkpoint")
    document.drawString(50, 58, "a: play or pause     v: play continuously     r: restart     e: finish")
    document.drawString(50, 36, "Ctrl+Left / Ctrl+Right: seek     [ / ]: change speed")
    document.setFont("Helvetica", 9)
    document.setFillColorRGB(.4, .4, .4)
    document.drawString(50, 15, "Timeline and PDF generated by vector_animation.py")
    document.showPage()
    document.save()
    return pdf, manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path("build/vector-example"))
    options = parser.parse_args()
    for filename in write_example(options.output_dir):
        print(filename)
